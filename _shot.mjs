import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
const PORT=8921, BASE='http://127.0.0.1:'+PORT, DATA='/tmp/vn-gate-'+Date.now();
const srv=spawn(process.execPath,['tools/serve.mjs'],{cwd:process.cwd(),env:Object.assign({},process.env,{PORT:String(PORT),DATA_DIR:DATA,APP_SECRET:'segredo-de-teste-1234',REGISTER_MAX:'50'}),stdio:'ignore'});
await new Promise(r=>setTimeout(r,2000));
const B=await chromium.launch({executablePath:process.env.CHROMIUM_PATH,args:['--no-sandbox','--disable-dev-shm-usage']});
const p=await B.newPage({viewport:{width:1440,height:900}});
const errs=[]; p.on('pageerror',e=>errs.push(e.message));
await p.goto(BASE+'/index.html',{waitUntil:'networkidle'});
await p.waitForTimeout(1500);
console.log('data-vn-auth:', await p.evaluate(()=>document.documentElement.getAttribute('data-vn-auth')));
console.log('gate visível:', await p.evaluate(()=>!!document.getElementById('vnGate')));
console.log('grafo no DOM:', await p.evaluate(()=>!!document.querySelector('#cy canvas')));
console.log('mensagem fecho:', (await p.evaluate(()=>{const n=document.getElementById('gateRegistoFechado');return n?n.textContent.slice(0,80):'(ausente)'})));
await p.screenshot({path:'docs/shot-34-login.png'});
await p.fill('#gateEmail','x@y.pt'); await p.fill('#gatePassword','errada1234X');
await p.click('#gateSubmit'); await p.waitForTimeout(1200);
console.log('erro mostrado:', (await p.evaluate(()=>{const n=document.getElementById('gateMsg');return n?n.textContent:'(nenhum)'})));
await p.screenshot({path:'docs/shot-35-login-erro.png'});
console.log('erros runtime:', errs.length?errs:'nenhum');
await B.close(); srv.kill();
